import { test } from "node:test";
import assert from "node:assert/strict";
import { PGlite } from "@electric-sql/pglite";
import { readFileSync, readdirSync } from "node:fs";
import request from "supertest";
import { createApp } from "../src/app";

test("arbitragem conectada: perfil próprio, convite privado, aceite autorizado, disponibilidade, conflito e cancelamento", async () => {
  const pg = new PGlite();
  for (const file of readdirSync("migrations").filter((f) => f.endsWith(".sql")).sort()) await pg.exec(readFileSync(`migrations/${file}`, "utf8"));
  const db = {
    query: async (sql: string, args?: any[]) => { const r = await pg.query(sql,args); return {rows:r.rows as any[],rowCount:r.affectedRows}; },
    transaction: async (run: any) => pg.transaction(async (tx) => run({query: async (sql: string, args?: any[]) => { const r = await tx.query(sql,args); return {rows:r.rows,rowCount:r.affectedRows}; }})),
  };
  const app = await createApp(db), http = app.getHttpServer();
  try {
    const create = async (name: string, team = true) => {
      const registered = await request(http).post("/auth/register").send({name:`Conta ${name}`,email:`${name}@example.com`,password:"senha-segura-123"}).expect(201);
      const auth = {Authorization:`Bearer ${registered.body.token}`};
      const state = async () => (await request(http).get("/state").set(auth).expect(200)).body;
      const act = async (action: any, status = 200) => (await request(http).post("/state").set(auth).send({version:(await state()).version,action}).expect(status)).body;
      if (team) await act({type:"registerTeam",name:`Time ${name}`,district:"Liberdade",city:"São Paulo",state:"SP",category:"Masculino",level:"Amador",bio:""});
      return {auth,state,act,id:(await state()).currentTeamId};
    };
    const a = await create("Alice"), b = await create("Bob"), c = await create("Carol"), d = await create("Dan");
    const r = await create("Carlos",false), line = await create("Ana",false);
    await request(http).get("/referee").expect(401);
    assert.deepEqual((await r.state()).arbitration,{profile:null,professionals:[],invites:[]});
    const professional = {type:"registerReferee",name:"Carlos Árbitro",city:"São Paulo",state:"SP",kind:"arbitro",bio:"Perfil acadêmico",available:true};
    await r.act({...professional,state:"XX"},400);
    await r.act({...professional,name:"A"},400);
    await r.act({...professional,available:undefined},400);
    await r.act(professional);
    await r.act(professional,409);
    await line.act({...professional,name:"Ana Bandeirinha",kind:"bandeirinha"});
    await a.act({...professional,name:"Organizador Árbitro"});
    const referee = (await r.state()).arbitration.profile, assistant = (await line.state()).arbitration.profile;
    assert.ok(referee.id && assistant.id && referee.id!==assistant.id);
    assert.equal((await r.state()).state.profile.role,"organizador","professional capability does not grant team organizer authority");
    assert.equal((await r.state()).state.teamRegistered,false);
    await r.act({type:"interest",id:a.id},403);
    const publicProfiles = (await a.state()).arbitration.professionals;
    assert.equal(publicProfiles.length,3);
    assert.ok(publicProfiles.every((p:any)=>!p.email&&!p.user_id),"public profile excludes account identifiers and credentials");
    const makeGame = async (one: typeof a, two: typeof b, field: string) => {
      await one.act({type:"interest",id:two.id}); await two.act({type:"interest",id:one.id});
      const res = await one.act({type:"schedule",id:two.id,date:new Date(Date.now()+7*86400000).toISOString().slice(0,10),time:"10:00",field,home:one.id});
      const game = res.state.games.find((g:any)=>g.status==="Aguardando adversário");
      await two.act({type:"acceptProposal",id:game.id});
      return game.id;
    };
    const ab = await makeGame(a,b,"Arena A"), cd = await makeGame(c,d,"Arena B");
    const invite = {type:"inviteReferee",id:ab,refereeId:referee.id,role:"arbitro"};
    await a.act(invite,409);
    await a.act({type:"pay",id:ab}); await c.act({type:"pay",id:cd});
    await c.act(invite,403);
    await a.act({...invite,role:"inexistente"},400);
    await a.act({...invite,refereeId:(await a.state()).arbitration.profile.id},403);
    await a.act({...invite,refereeId:assistant.id},400);
    await r.act({type:"refereeAvailable",value:false});
    await a.act(invite,409);
    await r.act({type:"refereeAvailable",value:true});
    await a.act(invite);
    let invitation = (await r.state()).arbitration.invites[0];
    assert.equal(invitation.gameId,ab);
    assert.equal(invitation.status,"Pendente");
    assert.equal(invitation.teamAName.includes("Time"),true);
    assert.deepEqual((await line.state()).arbitration.invites,[]);
    const apiSnapshot = await request(http).get("/referee").set(r.auth).expect(200);
    assert.equal(apiSnapshot.body.invites[0].id,invitation.id);
    await a.act(invite,409);
    await a.act({type:"respondReferee",id:invitation.id,accept:true},403);
    await line.act({type:"respondReferee",id:invitation.id,accept:true},403);
    await c.act({type:"respondReferee",id:invitation.id,accept:true},403);
    await r.act({type:"respondReferee",id:invitation.id,accept:false});
    await r.act({type:"respondReferee",id:invitation.id,accept:true},409);
    assert.equal((await a.state()).state.games.find((g:any)=>g.id===ab).referee,"Pendente");
    await a.act(invite);
    invitation = (await r.state()).arbitration.invites.find((i:any)=>i.status==="Pendente");
    await r.act({type:"refereeAvailable",value:false});
    await r.act({type:"respondReferee",id:invitation.id,accept:true},409);
    await r.act({type:"refereeAvailable",value:true});
    await r.act({type:"respondReferee",id:invitation.id,accept:true});
    assert.equal((await b.state()).state.games.find((g:any)=>g.id===ab).referee,"Carlos Árbitro");
    assert.ok((await b.state()).state.games.find((g:any)=>g.id===ab).refereeAssignments.some((x:any)=>x.id===invitation.id&&x.status==="Aceito"));
    await r.act({...professional,type:"refereeProfile",kind:"bandeirinha"},409);
    await c.act({...invite,id:cd});
    const conflict = (await r.state()).arbitration.invites.find((i:any)=>i.gameId===cd);
    await r.act({type:"respondReferee",id:conflict.id,accept:true},409);
    await r.act({type:"respondReferee",id:conflict.id,accept:false});
    await c.act({...invite,id:cd,refereeId:assistant.id,role:"bandeirinha1"});
    const lineInvite = (await line.state()).arbitration.invites[0];
    await c.act({...invite,id:cd,refereeId:assistant.id,role:"bandeirinha2"},409);
    await line.act({type:"respondReferee",id:lineInvite.id,accept:true});
    await line.act({...professional,type:"refereeProfile",name:"Ana Atualizada",kind:"bandeirinha",id:referee.id,user_id:"outro"});
    assert.equal((await r.state()).arbitration.profile.name,"Carlos Árbitro");
    assert.equal((await line.state()).arbitration.profile.id,assistant.id);
    await a.act({type:"cancel",id:ab,reason:"Cancelamento da partida para liberar agenda"});
    assert.equal((await r.state()).arbitration.invites.find((i:any)=>i.id===invitation.id).status,"Cancelado");
    await c.act({...invite,id:cd});
    const free = (await r.state()).arbitration.invites.find((i:any)=>i.gameId===cd&&i.status==="Pendente");
    await r.act({type:"respondReferee",id:free.id,accept:true});
    await c.act({type:"cancel",id:cd,reason:"Chuva forte",weather:true});
    assert.equal((await r.state()).arbitration.invites.find((i:any)=>i.id===free.id).status,"Aceito");
    await d.act({type:"weatherAgree",id:cd});
    assert.equal((await r.state()).arbitration.invites.find((i:any)=>i.id===free.id).status,"Cancelado");
    assert.equal((await line.state()).arbitration.invites[0].status,"Cancelado");
    await r.act({type:"respondReferee",id:free.id,accept:true},409);
    await assert.rejects(() => db.query("INSERT INTO game_referees(id,game_id,referee_id,invited_by_team_id,role) VALUES('bad',$1,'missing',$2,'arbitro')",[ab,a.id]),/foreign key/i);
  } finally { await app.close(); await pg.close(); }
});
